/**
 * Turns the us-atlas topojson (already projected to Albers USA) into the SVG
 * paths and label positions the app draws, so the phone doesn't ship d3-geo,
 * topojson-client or the 80 KB topojson, nor compute any of it on startup.
 *
 * Run `npm run build:map` after changing scripts/data/states-albers-10m.json.
 * The output, src/js/map-shapes.js, is committed.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { geoPath } from "d3-geo";
import { feature } from "topojson-client";

const here = (path) => fileURLToPath(new URL(path, import.meta.url));

const topology = JSON.parse(readFileSync(here("./data/states-albers-10m.json"), "utf-8"));
const geo = feature(topology, topology.objects.states);
const pathGen = geoPath();

const [, [x1, y1]] = pathGen.bounds(geo);
const round = (n) => Math.round(n * 100) / 100;

const shapes = geo.features.map((d) => ({
  fips: d.id,
  name: d.properties.name,
  d: pathGen(d),
  centroid: pathGen.centroid(d).map(round),
}));

const output = `// Generated by scripts/build-map.mjs from the us-atlas topojson. Do not edit.
export const MAP_WIDTH = ${Math.ceil(x1)};
export const MAP_HEIGHT = ${Math.ceil(y1)};
export const MAP_SHAPES = ${JSON.stringify(shapes, null, 0).replace(/\},\{/g, "},\n{")};
`;

writeFileSync(here("../src/js/map-shapes.js"), output);
console.log(`map-shapes.js: ${shapes.length} shapes, ${output.length} bytes`);
